grant all on all tables in schema "landingOsorIA" to service_role;
grant all on all sequences in schema "landingOsorIA" to service_role;
grant select on
  "landingOsorIA".github_repos,
  "landingOsorIA".github_stats_snapshots,
  "landingOsorIA".github_yearly_contributions
  to anon, authenticated;
grant execute on all functions in schema "landingOsorIA" to service_role;

alter default privileges in schema "landingOsorIA"
  grant all on tables to service_role;
alter default privileges in schema "landingOsorIA"
  grant all on sequences to service_role;
